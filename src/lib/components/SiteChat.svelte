<script lang="ts">
	import Icon from './Icon.svelte';
	import { consent } from '$lib/consent.svelte';

	/**
	 * The site chat: a launcher in the site's own button style, and chat-aide's widget
	 * (plain theme, re-skinned below) once somebody asks for it. The server half is in
	 * src/hooks.server.ts.
	 *
	 * The widget is imported on the first press, not with the page. Most visitors never open
	 * it, so they download none of it — and the widget writes a session id to
	 * `sessionStorage` as soon as it mounts, which this way happens only after the visitor
	 * has asked for the chat (/datenschutz relies on that).
	 *
	 * The launcher stays out of the prerendered HTML (it needs JavaScript to do anything) and
	 * steps aside while the consent banner is asking: both sit at the bottom of the viewport,
	 * and the banner is the one that needs an answer.
	 */
	type ChatWidget = typeof import('@chat-aide/sveltekit/themes/plain').ChatWidget;

	let Widget = $state<ChatWidget | null>(null);
	let open = $state(false);
	let loading = false;

	async function toggle() {
		if (Widget) {
			open = !open;
			return;
		}
		if (loading) return;
		loading = true;
		try {
			Widget = (await import('@chat-aide/sveltekit/themes/plain')).ChatWidget;
			open = true;
		} finally {
			loading = false;
		}
	}

	const strings = {
		title: 'Ask this site',
		greeting:
			"Ask about anything written or built here. Answers are generated by an AI model from this site's pages and can be wrong.",
		placeholder: 'Ask a question…',
		open: 'Ask this site',
		close: 'Close chat'
	};

	const disclosure =
		"Your messages and this page's address are processed by Cloudflare Workers AI. Please don't share personal data. Details under Datenschutz in the footer.";
</script>

<div class="chat" data-aide-ignore>
	{#if consent.ready && !consent.asking}
		<button
			type="button"
			class="btn btn--secondary chat__launcher"
			aria-haspopup="dialog"
			aria-expanded={open}
			onclick={toggle}
		>
			<Icon name="message" />
			Ask this site
		</button>
	{/if}

	{#if Widget}
		<!-- An empty launcher snippet: the button above is the launcher, and it has to exist
		     before the widget does. Keeping it outside also keeps it focused across the first
		     press, so the dialog hands focus back to it on close. -->
		<Widget bind:open theme="dark" persistThread={false} {strings} {disclosure}>
			{#snippet launcher()}{/snippet}
		</Widget>
	{/if}
</div>

<style>
	/* Layers (DESIGN.md §6): the launcher sits under the consent banner (90), the open
	   window over it (95) — the visitor opened that on purpose. The skip link (100) stays
	   on top of both. */
	.chat {
		--chat-x: var(--gutter);
		--chat-y: max(var(--s-5), env(safe-area-inset-bottom));
	}

	.chat__launcher {
		position: fixed;
		z-index: 80;
		right: var(--chat-x);
		bottom: var(--chat-y);
		/* `.btn` goes full width below 480px; a floating control must not. */
		width: auto;
		box-shadow: var(--shadow-3), var(--shadow-inset);
	}

	@media (hover: hover) and (pointer: fine) {
		/* `.btn--secondary` drops its icon on hover, which is the download arrow's motion.
		   A speech bubble has no direction to move in. */
		.chat__launcher:hover :global(svg) {
			transform: none;
		}
	}

